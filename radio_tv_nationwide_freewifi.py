RADIO_RENDER_BASE = "https://ajiousama-radiko.onrender.com/radio-tv"
RADIO_BUILD = "20260908a"
VERCEL_RADIKO_SIDS = {
    "JOEU-FM", "RNB", "LFR", "QRR", "TBS", "FMT",
    "ABC", "CCL", "802", "FMO", "MBS", "OBC", "KBS",
    "ALPHA-STATION", "E-RADIO", "CRK",
}
# These nationwide stations use the Render image+audio mux immediately. Their
# stable station-art TS assets already exist, while Vercel is currently rate-limited.
RENDER_RADIKO_SIDS = {"HBC", "TBC", "CBC", "RCC", "RKB", "KBC"}
VERCEL_NHK_SIDS = {"nhk_r1_matsuyama"}
ALL_RADIKO_SIDS = VERCEL_RADIKO_SIDS | RENDER_RADIKO_SIDS
LOGO_RAW_BASE = "https://raw.githubusercontent.com/ajiousama/himitsu/main"
EXPECTED_RADIO_COUNT = 28
EXPECTED_RADIKO_COUNT = 22
EXPECTED_VERCEL_ROUTE_COUNT = 17


def radio_url(sid: str) -> str:
    if sid in VERCEL_RADIKO_SIDS or sid in VERCEL_NHK_SIDS:
        return f"{RADIO_VERCEL_BASE}{quote(sid, safe='')}"
    return f"{RADIO_RENDER_BASE}/{quote(sid, safe='')}?v={RADIO_BUILD}"


def source_logo_url(sid: str) -> str:
    return f"https://radiko.jp/v2/static/station/logo/{sid}/lrtrim/688x160.png"


def safe_slug(value: str) -> str:
    value = re.sub(r"[^A-Za-z0-9_.-]+", "_", value.strip())
    return value.strip("._-") or "logo"


def contrast_logo_url(tvgid: str, sid: str) -> str:
    source = source_logo_url(sid)
    digest = hashlib.sha1(source.encode("utf-8")).hexdigest()[:8]
    relpath = f"logos/contrast/{safe_slug(tvgid)}_{digest}.png"
    return f"{LOGO_RAW_BASE}/{urllib.parse.quote(relpath, safe='/._-')}"


def radio_entry(tvgid: str, station: str, name: str, logo: str) -> str:
    return (
        f'#EXTINF:-1 tvg-id="{tvgid}" tvg-logo="{logo}" group-title="ラジオ",{name}\n'
        f'{radio_url(station)}\n'
    )


def radiko_entry(tvgid: str, sid: str, name: str, logo: str | None = None) -> str:
    if logo is None:
        # Use the local white-card asset generated by logo_contrast_apply.py.
        # This keeps black-background IPTV clients from swallowing dark or
        # transparent station artwork.
        logo = contrast_logo_url(tvgid, sid)
    return radio_entry(tvgid, sid, name, logo)


