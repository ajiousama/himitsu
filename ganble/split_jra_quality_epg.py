from copy import deepcopy
from pathlib import Path
import xml.etree.ElementTree as ET

EPG = Path(__file__).resolve().parent / 'epg.xml'

JRA = {
    'jra.gch': ('jra.gch', 'グリーンチャンネル'),
    'jra.east': ('jra.east', 'JRA EAST WEB3'),
    'jra.west': ('jra.west', 'JRA WEST WEB4'),
    'jra.hokkaido': ('jra.local', 'JRA LOCAL WEB5'),
}


def set_display_name(channel, text):
    node = channel.find('display-name')
    if node is None:
        node = ET.SubElement(channel, 'display-name')
    node.text = text


def main():
    if not EPG.exists():
        raise SystemExit('epg.xml not found')

    tree = ET.parse(EPG)
    root = tree.getroot()

    split_ids = {f'{out_base}.hq' for out_base, _ in JRA.values()} | {f'{out_base}.lq' for out_base, _ in JRA.values()}

    # Capture the legacy JRA channels/programmes generated by main_epg_3days.py.
    source_channels = {ch.get('id'): ch for ch in root.findall('channel') if ch.get('id') in JRA}
    source_programmes = {
        base: [p for p in root.findall('programme') if p.get('channel') == base]
        for base in JRA
    }
    has_legacy = bool(source_channels) or any(source_programmes.values())
    has_split = any(ch.get('id') in split_ids for ch in root.findall('channel'))

    # A normalized EPG can invoke this script again. Preserve already-split data.
    if not has_legacy and has_split:
        print('JRA quality EPG: already split, keeping existing HQ/LQ data')
        return

    if not has_legacy:
        raise SystemExit('No legacy JRA EPG channels found to split')

    # Remove stale split copies so conversion from legacy IDs is deterministic.
    for node in list(root):
        if node.tag == 'channel' and node.get('id') in split_ids:
            root.remove(node)
        elif node.tag == 'programme' and node.get('channel') in split_ids:
            root.remove(node)

    # Build HQ/LQ channels and clone the exact same programme data to both.
    for base, (out_base, display) in JRA.items():
        src_ch = source_channels.get(base)
        programmes = source_programmes.get(base, [])
        for quality, label in (('hq', 'HQ'), ('lq', 'LQ')):
            new_id = f'{out_base}.{quality}'
            if src_ch is not None:
                new_ch = deepcopy(src_ch)
                new_ch.set('id', new_id)
            else:
                new_ch = ET.Element('channel', id=new_id)
            set_display_name(new_ch, f'{display} {label}')
            root.append(new_ch)

            for prog in programmes:
                copied = deepcopy(prog)
                copied.set('channel', new_id)
                root.append(copied)

    # Legacy unsuffixed JRA IDs are no longer exposed after split.
    for node in list(root):
        if node.tag == 'channel' and node.get('id') in JRA:
            root.remove(node)
        elif node.tag == 'programme' and node.get('channel') in JRA:
            root.remove(node)

    ET.indent(tree, space='  ')
    tree.write(EPG, encoding='utf-8', xml_declaration=True)
    print('JRA EPG split complete: GCH/EAST/WEST/LOCAL -> 8 HQ/LQ channel IDs')


if __name__ == '__main__':
    main()
